@typing.final
@dataclasses.dataclass(frozen=True, kw_only=True)
class Exit[**ParamT, RetT](
    decorator.Exit[
        ParamT,
        RetT,
        _Decoratee[ParamT, RetT],
        _Receive[ParamT, RetT],
        _Send[ParamT, RetT],
        _Exit[ParamT, RetT],
        _Enter[ParamT, RetT],
        _Decorated[ParamT, RetT],
        _Decorator[ParamT, RetT],
    ],
    herd_.Exit[
        ParamT,
        RetT,
        _Decoratee[ParamT, RetT],
        _Receive[ParamT, RetT],
        _Send[ParamT, RetT],
        _Exit[ParamT, RetT],
        _Enter[ParamT, RetT],
        _Decorated[ParamT, RetT],
        _Decorator[ParamT, RetT],
        _Future[RetT],
    ],
):
    future: _Future[RetT] = dataclasses.field(default_factory=concurrent.futures.Future)

    def __call__(self, result: decorator.Raise | RetT) -> tuple[()]:
        self.enter.decorated.future_by_key.pop(self.key, None)
        self.future.set_result(result)

        return ()


@typing.final
@dataclasses.dataclass(frozen=True, kw_only=True)
class Enter[**ParamT, RetT](
    decorator.Enter[
        ParamT,
        RetT,
        _Decoratee[ParamT, RetT],
        _Receive[ParamT, RetT],
        _Send[ParamT, RetT],
        _Exit[ParamT, RetT],
        _Enter[ParamT, RetT],
        _Decorated[ParamT, RetT],
        _Decorator[ParamT, RetT],
    ],
    herd_.Enter[
        ParamT,
        RetT,
        _Decoratee[ParamT, RetT],
        _Receive[ParamT, RetT],
        _Send[ParamT, RetT],
        _Exit[ParamT, RetT],
        _Enter[ParamT, RetT],
        _Decorated[ParamT, RetT],
        _Decorator[ParamT, RetT],
    ],
):
    # TODO(claude): Dedup this with the asyncio version.
    def __call__(
        self, *args: ParamT.args, **kwargs: ParamT.kwargs,
    ) -> tuple[_Exit[ParamT, RetT], _Decoratee[ParamT, RetT]] | tuple[typing.Callable[ParamT, RetT]]:
        key = self.create_key(*args, **kwargs)
        future = self.decorated.future_by_key.get(key)
        match future is None:
            case True:
                future = self.decorated.future_by_key[key] = concurrent.futures.Future()
                return self.exit_t(enter=self, future=future, key=key), self.decorated.decoratee
            case False:
                return (lambda *_args, **_kwargs: future.result()),
        assert False, "Unreachable"


