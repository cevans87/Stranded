@typing.final
@dataclasses.dataclass(frozen=True, kw_only=True)
class Decorated[**_Param, _Ret](
    decorator.Decorated[
        _Param,
        _Ret,
        _Decoratee[_Param, _Ret],
        _Exit[_Param, _Ret],
        _Enter[_Param, _Ret],
        _Decorator[_Param, _Ret],
    ],
    map_.Decorated[
        _Param,
        _Ret,
        _Decoratee[_Param, _Ret],
        _Exit[_Param, _Ret],
        _Enter[_Param, _Ret],
        _Decorator[_Param, _Ret],
    ],
):
    @typing.override
    def __call__(
        self,
        params: typing.Iterable[tuple[_Param.args, _Param.kwargs]],
        /,
    ) -> typing.Iterable[_Ret]:
        q = queue.LifoQueue()
        n = 0
        condition = threading.Condition()

        def runner(*args: _Param.args, **kwargs: _Param.kwargs) -> None:
            nonlocal n, self
            try:
                _ret = self.decoratee(*args, **kwargs)
            except Exception as _e:
                q.put(_e)
            else:
                q.put(_ret)

            with condition:
                n -= 1
                if n == 0:
                    condition.notify()

        def submitter() -> None:
            nonlocal n
            for (args, kwargs) in params:
                with condition:
                    n += 1
                self.decorator.pool.submit(runner, *args, **kwargs)

            with condition:
                condition.wait_for(lambda: n == 0)

            q.shutdown()

        concurrent.futures.ThreadPoolExecutor(max_workers=1).submit(submitter)

        while True:
            try:
                result = q.get()
            except queue.ShutDown:
                break

            match result:
                case Exception() as e:
                    raise e
                case ret:
                    yield ret


